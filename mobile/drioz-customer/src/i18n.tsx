const dictionaries: Record<Locale, Dict> = { en, hi, te };
export type T = (key: string, vars?: Record<string, string | number>) => string;
export function translate(locale: Locale, key: string, vars?: Record<string, string | number>) {
  let text = dictionaries[locale][key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.split(`{${k}}`).join(String(v));
  return text;
}

const I18nContext = createContext<{ locale: Locale; setLocale: (l: Locale) => void; t: T }>({
  locale: "en",
  setLocale: () => {},
  t: (key, vars) => translate("en", key, vars),
});

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("en");
  useEffect(() => {
    SecureStore.getItemAsync(STORE_KEY)
      .then((v) => {
        if (v === "hi" || v === "te" || v === "en") setLocaleState(v);
      })
      .catch(() => {});
  }, []);
  const setLocale = useCallback((l: Locale) => {
    setLocaleState(l);
    SecureStore.setItemAsync(STORE_KEY, l).catch(() => {});
  }, []);
  const t = useCallback<T>((key, vars) => translate(locale, key, vars), [locale]);
  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}
export const useI18n = () => useContext(I18nContext);
