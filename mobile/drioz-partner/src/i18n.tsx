const dictionaries: Record<Lang, Record<Key, string>> = { en, hi, te };
const STORE = "drioz.partner.lang";
export type T = (key: Key, vars?: Record<string, string | number>) => string;
const format = (text: string, vars?: Record<string, string | number>) =>
  vars ? text.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? String(vars[k]) : `{${k}}`)) : text;
const make = (lang: Lang): T => (key, vars) => format(dictionaries[lang][key] ?? en[key] ?? key, vars);

const I18n = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: T }>({ lang: "en", setLang: () => {}, t: make("en") });

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  useEffect(() => {
    SecureStore.getItemAsync(STORE)
      .then((v) => {
        if (v === "hi" || v === "te" || v === "en") setLangState(v);
      })
      .catch(() => {});
  }, []);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    SecureStore.setItemAsync(STORE, l).catch(() => {});
  }, []);
  const value = useMemo(() => ({ lang, setLang, t: make(lang) }), [lang, setLang]);
  return <I18n.Provider value={value}>{children}</I18n.Provider>;
}
export const useT = () => useContext(I18n).t;
export const useLang = () => useContext(I18n);
